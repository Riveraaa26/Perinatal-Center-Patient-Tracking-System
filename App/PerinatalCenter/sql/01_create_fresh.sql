-- PostgreSQL: выполнять от владельца БД только на НОВОЙ пустой базе.
-- Здесь НЕТ паролей и персональных данных.
BEGIN;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE role (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name TEXT NOT NULL UNIQUE
);
CREATE TABLE employee (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    sour_name TEXT NOT NULL,
    role_id INTEGER NOT NULL REFERENCES role(id),
    block BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE authorizations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL UNIQUE REFERENCES employee(id) ON DELETE RESTRICT,
    login TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL
);
CREATE TABLE department (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL DEFAULT 'ward' CHECK(kind IN ('ward','operating','postpartum')),
    department_name TEXT NOT NULL UNIQUE,
    chamber_capacity INTEGER NOT NULL DEFAULT 0,
    chamber_capacity_disease INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE chamber (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number INTEGER NOT NULL CHECK(number > 0),
    capacity INTEGER NOT NULL CHECK(capacity > 0),
    department_id INTEGER NOT NULL REFERENCES department(id) ON DELETE RESTRICT,
    disease BOOLEAN NOT NULL DEFAULT FALSE,
    current_load INTEGER NOT NULL DEFAULT 0 CHECK(current_load >= 0 AND current_load <= capacity),
    UNIQUE(department_id, number)
);
CREATE TABLE patient (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    sour_name TEXT NOT NULL,
    policy TEXT NOT NULL UNIQUE CHECK(policy ~ '^[0-9]{16}$'),
    pregnancy_period TEXT NOT NULL,
    disease BOOLEAN NOT NULL DEFAULT FALSE,
    discharge_date TIMESTAMPTZ,
    discharge_recommendations TEXT
);
CREATE TABLE transfer (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patient(id) ON DELETE RESTRICT,
    employee_id INTEGER NOT NULL REFERENCES employee(id) ON DELETE RESTRICT,
    chamber_id INTEGER REFERENCES chamber(id) ON DELETE RESTRICT,
    date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employee(id) ON DELETE RESTRICT,
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    target_id INTEGER NOT NULL,
    at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_transfer_patient_latest ON transfer(patient_id,id DESC);
CREATE INDEX IF NOT EXISTS idx_transfer_chamber ON transfer(chamber_id);
CREATE INDEX IF NOT EXISTS idx_chamber_department ON chamber(department_id);
INSERT INTO role(role_name) VALUES ('Администратор'),('Медсестра'),('Врач акушер-гинеколог'),('Заведующая отделением') ON CONFLICT (role_name) DO NOTHING;
COMMIT;
