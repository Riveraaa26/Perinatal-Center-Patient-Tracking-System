-- Миграция для старой схемы Сани: НЕ удаляет пациенток и историю переводов.
-- Запускать единожды в нужной БД от владельца/администратора.
BEGIN;
-- В ТОМ ЖЕ сеансе на тестовой КОПИИ: SET perinatal.migration_target = 'точное_имя_копии';
DO $$ BEGIN
    IF current_setting('perinatal.migration_target',true) IS DISTINCT FROM current_database() THEN
        RAISE EXCEPTION 'Укажите имя тестовой копии в perinatal.migration_target';
    END IF;
    IF EXISTS (SELECT FROM pg_trigger WHERE tgrelid IN ('transfer'::regclass,'chamber'::regclass) AND NOT tgisinternal) THEN
        RAISE EXCEPTION 'Сначала согласуйте пользовательские триггеры transfer/chamber';
    END IF;
END $$;
LOCK TABLE patient, transfer, chamber, department, authorizations IN ACCESS EXCLUSIVE MODE;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

ALTER TABLE authorizations ALTER COLUMN password TYPE TEXT;
ALTER TABLE patient ADD COLUMN IF NOT EXISTS discharge_date TIMESTAMPTZ;
ALTER TABLE patient ADD COLUMN IF NOT EXISTS discharge_recommendations TEXT;
ALTER TABLE transfer ALTER COLUMN chamber_id DROP NOT NULL;
ALTER TABLE transfer ALTER COLUMN date SET DEFAULT CURRENT_TIMESTAMP;
-- Неизвестную историческую дату сохраняем как NULL.
ALTER TABLE department ADD COLUMN IF NOT EXISTS kind TEXT;
UPDATE department SET kind=CASE department_name
    WHEN 'Послеродовое отделение' THEN 'postpartum'
    WHEN 'Операционный блок' THEN 'operating'
    ELSE 'ward' END WHERE kind IS NULL;
ALTER TABLE department ALTER COLUMN kind SET DEFAULT 'ward', ALTER COLUMN kind SET NOT NULL;

DO $$ BEGIN
    IF EXISTS (SELECT FROM authorizations WHERE password IS NULL OR password='' OR
        (password !~ '^[$]2[aby][$][0-9]{2}[$][./A-Za-z0-9]{53}$' AND
        (left(password,1)='$' OR octet_length(password)>72 OR
         current_setting('perinatal.legacy_plaintext',true) IS DISTINCT FROM 'confirmed'))) THEN
        RAISE EXCEPTION 'Формат паролей требует сверки. Для подтвержденного открытого текста на копии задайте perinatal.legacy_plaintext=confirmed';
    END IF;
END $$;
UPDATE authorizations SET password=crypt(password,gen_salt('bf',12)) WHERE left(password,1) <> '$';
CREATE UNIQUE INDEX IF NOT EXISTS pc_unique_policy ON patient(policy);
CREATE UNIQUE INDEX IF NOT EXISTS pc_unique_login ON authorizations(login);
CREATE UNIQUE INDEX IF NOT EXISTS pc_unique_room ON chamber(department_id,number);
CREATE TABLE IF NOT EXISTS audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employee(id) ON DELETE RESTRICT,
    action TEXT NOT NULL,
    target TEXT NOT NULL,
    target_id INTEGER NOT NULL,
    at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_transfer_patient_latest ON transfer(patient_id,id DESC);
CREATE INDEX IF NOT EXISTS idx_transfer_chamber ON transfer(chamber_id);
CREATE INDEX IF NOT EXISTS idx_chamber_department ON chamber(department_id);
-- Восстанавливаем физическую загруженность по последней записи каждой пациентки.
WITH latest AS (
    SELECT DISTINCT ON(patient_id) patient_id,chamber_id FROM transfer ORDER BY patient_id,id DESC
), loads AS (
    SELECT chamber_id,count(*)::integer AS occupied FROM latest
    WHERE chamber_id IS NOT NULL GROUP BY chamber_id
)
UPDATE chamber AS c SET current_load = COALESCE((SELECT occupied FROM loads WHERE loads.chamber_id = c.id),0);
DO $$ BEGIN
    IF EXISTS (SELECT FROM chamber WHERE current_load > capacity OR capacity < 1 OR current_load IS NULL) THEN
        RAISE EXCEPTION 'Размещение противоречит вместимости, изменения отменены';
    END IF;
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='chamber'::regclass AND conname='pc_chamber_load') THEN
        ALTER TABLE chamber ADD CONSTRAINT pc_chamber_load CHECK(current_load BETWEEN 0 AND capacity AND capacity>0);
    END IF;
END $$;
COMMIT;
